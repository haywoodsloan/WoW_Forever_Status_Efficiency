"""Breaks the Status Efficiency addon one way at a time and says whether the
scenarios notice. Written for 0.3.4 (commit 2381f83): how a cast is judged by
the change reports of the unit it was aimed at. The entries labelled
"tooltip:", "empty:", "blind:" and "report:" came with 0.3.5: which times in a
tooltip count as an effect's length, and how soon a skill that leaves nothing
loses its icon. Those labelled "kinds:" and "death:" came with 0.3.6: a report
that only took effects away is never a cast landing, and an enemy dying right
after a skill was used teaches nothing about the skill. "login:" came with
0.3.7: the addon says nothing in chat when it loads. "fight:" came with 0.3.8:
the icons stay on all through a fight, your own or one that someone in your
group is in close by. "when:" came with 0.3.9, written by the options work:
the three choices for when the icons appear. "stacks:", "others:", "wait:",
"late:" and "said:" came with 0.4.0: an effect that stacks is counted,
another player's copy of an effect a unit carries only once counts like
yours, a skill is held to the frame of its cast once its landings have shown
there, and what came too late for such a cast is kept in the saved report.
"columns:" came with 0.4.1, written by the options work: the Stacks box and
the Shared tick in each row of the Spells tab, the reason under a spell's
name, and Enter in a box that was not changed.
"full:" and "immune:" came with 0.4.2: an effect that stacks only counts as
there once it is on in full, and an enemy the game calls immune to a spell in
the moment of a cast of yours is left out when the spell is judged.
"panel:" came with 0.5.0, written by the options work: the settings panel
rebuilt as three tabs (Display, Icons, Skills) with one setting to a row, a
skill's own picture, and the Immune row. The "when:" and "columns:" entries
that broke the old panel went with it; the ones still here hold the same
rules in the new one.
With 0.5.1 the options work reworded every sentence of the panel and added
the two groups of the Skills tab (all offensive skills, all defensive
skills), whose settings change at once: the "when:", "columns:" and "panel:"
entries that quoted the old sentences or the old pane were replaced by ones
that hold the same rules in the new one, and the entries for the groups are
labelled "panel:" as well.
"chat:" came with 0.5.2: every answer of a /se command and every notice in
chat is a whole sentence in the words of the panel, and /se list gives the
reasons the Skills tab gives. The older entries that quoted a line of chat
(three of the "when:" ones among them) were brought to the new sentences.
The "panel:" entries that came with 0.5.3 are for a client that makes no
typing box: each figure of the panel then stands there as plain words, the
sentence with it names the chat command that changes it, and a result goes
by the word that command takes (green, yellow or red).
"shield:", "proof:", "aim:" and "reach:" came with 0.5.4: an enemy the game
calls immune keeps its red X instead of losing it after twelve seconds, a
passing shield is told from a lasting immunity by what else the enemy turns
away and by the hits that land on it, a skill for one enemy is judged on the
enemies of the fight while none is targeted, and a skill that hits all around
you leaves out the enemies standing further off than it reaches. The "immune:"
entries for the twelve seconds went with that rule.
"plates:", "sight:" and the newer "blind:" entries came with 0.5.5: what the
addon does when enemy nameplates are off (turn them back on and say so, only
say so, or nothing, and never during a fight), how it knows that there are no
nameplates to go by, which enemies stand in for them then, and what the saved
report keeps of it. A secret answer about the game's setting that is compared
all the same is not among them: the pretend client cannot make "==" fail on a
secret value, so no scenario could notice.
The "panel:" entries that came with 0.5.6, written by the options work, are
for the row "If nameplates are off" on the Display tab: its three choices are
the addon's own, each named, explained and worded for chat as the addon does
it, the line under them says what is so right now, the row is greyed while
the icons are off, Defaults puts it back, and from that row down nothing on
the tab lies on what stands above it.

This file lives in the repository it checks (tools/checks), so the list always
fits the commit it came with. On Windows the command is `python` or `py -3`.

  python3 break_one_at_a_time.py --check        only say which entries no longer fit the code
                                                (reads the checkout this file is in, changes nothing)
  SE_REPO=/path/to/copy python3 break_one_at_a_time.py [word ...]
                                                break the copy, one entry at a time; with
                                                words, only the labels holding one of them
  SE_SLICE=2/4 ...                              only the second of four equal shares of the
                                                entries, so that four copies of the repository
                                                (each named with SE_REPO) can share a full run
  SE_ONLY=/path/to/file ...                     only the entries whose labels the file lists,
                                                one to a line
  python3 break_one_at_a_time.py --jobs 12 --scratch /path/to/empty/folder [word ...]
                                                the same run in twelve shares at once: makes
                                                twelve copies of this checkout's StatusEfficiency
                                                and tests folders under the scratch folder
                                                (--tree names another checkout), runs
                                                one share on each (below normal priority on
                                                Windows, so that a game stays smooth), writes
                                                share1.txt and so on there, and prints at the end
                                                what was not caught. The checkout is only read.

A run that breaks anything needs SE_REPO, and it should name a scratch copy of
the repository: files are changed on disk while the suite runs, so the tree
being worked on is no place for it. (A copy of the folder without .git is
good enough.) Never import this file from another script to get at its list:
read the list with ast.

Each entry: (label, file, old text, new text). The old text must occur exactly
once in the file, or the entry is reported with "??" and skipped: that means
the code moved on and the entry needs bringing up to date. Every file is put
back as it was, also when the run is stopped with Ctrl-C or kill. A full run
starts the suite once per entry (it plays every scenario two ways and stops
after the first that fails, about five seconds for an entry that is caught and
twenty for one that is not).

An entry that is not caught is either a rule no scenario holds the addon to,
which wants a scenario, or a change nothing could ever show, which wants the
entry dropped (and perhaps the code it changes, too).
"""
