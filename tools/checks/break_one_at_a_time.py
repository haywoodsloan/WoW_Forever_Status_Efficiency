def run(words=()):
    # UTF-8 both ways whatever the computer's own code page is (Windows).
    out = subprocess.run([sys.executable, str(ROOT / 'tests' / 'run_tests.py'), '--stop-early', *words],
                         capture_output=True, encoding='utf-8', errors='replace', timeout=600,
                         env=dict(os.environ, PYTHONUTF8='1'))
    last = out.stdout.strip().splitlines()[-1] if out.stdout.strip() else out.stderr[-200:]
    failed = [line[4:] for line in out.stdout.splitlines() if line.startswith('--- ')]
    return last, failed


def stopped(signum, frame):
    # Leave through the `finally` that puts the file back.
    raise SystemExit('stopped by signal %d' % signum)


def taken(args, name):
    """Takes `name value` out of the list of arguments and returns the value."""
    if name not in args:
        return None
    at = args.index(name)
    if at + 1 >= len(args):
        raise SystemExit('%s wants a value' % name)
    value = args[at + 1]
    del args[at:at + 2]
    return value


def together(jobs, tree, scratch, words):
    """The whole run in `jobs` shares at once, each on its own copy of the tree under `scratch`."""
    tree, scratch = Path(tree).resolve(), Path(scratch).resolve()
    for part in ('StatusEfficiency', 'tests'):
        if not (tree / part).is_dir():
            raise SystemExit('%s has no %s folder: name the checkout with --tree' % (tree, part))
    scratch.mkdir(parents=True, exist_ok=True)
    began = time.time()
    quiet = {}
    if os.name == 'nt':
        quiet['creationflags'] = subprocess.BELOW_NORMAL_PRIORITY_CLASS
    running = []
    try:
        for share in range(1, jobs + 1):
            copy = scratch / ('c%d' % share)
            if copy.exists():
                shutil.rmtree(copy)
            for part in ('StatusEfficiency', 'tests'):
                shutil.copytree(tree / part, copy / part, ignore=shutil.ignore_patterns('__pycache__'))
            log = open(scratch / ('share%d.txt' % share), 'w', encoding='utf-8')
            env = dict(os.environ, SE_REPO=str(copy), SE_SLICE='%d/%d' % (share, jobs), PYTHONUTF8='1')
            running.append((subprocess.Popen([sys.executable, str(Path(__file__).resolve()), *words],
                                             stdout=log, stderr=subprocess.STDOUT, env=env, **quiet), log))
        codes = [process.wait() for process, log in running]
    finally:
        for process, log in running:
            if process.poll() is None:
                process.kill()
            log.close()
    caught, told, unfinished = 0, [], []
    for share, code in enumerate(codes, 1):
        lines = (scratch / ('share%d.txt' % share)).read_text(encoding='utf-8').splitlines()
        caught += sum(1 for line in lines if line.startswith('caught  '))
        told += [line for line in lines if line.startswith(('MISSED', '??'))]
        if code != 0 or not any(' not caught: ' in line for line in lines):
            unfinished.append('share %d ended with code %s: %s' % (share, code, ' | '.join(lines[-3:])))
    for line in told + unfinished:
        print(line)
    print()
    print('%d caught, %d missed or out of date, %d shares that did not finish, in %d seconds with %d shares at once'
          % (caught, len(told), len(unfinished), time.time() - began, jobs))
    return 1 if told or unfinished else 0


def main():
    if hasattr(sys.stdout, 'reconfigure'):
        sys.stdout.reconfigure(encoding='utf-8', errors='replace')
    only = sys.argv[1:]
    jobs, tree, scratch = taken(only, '--jobs'), taken(only, '--tree'), taken(only, '--scratch')
    if jobs:
        if not scratch or '--check' in only:
            raise SystemExit('--jobs wants --scratch, an empty folder for the copies, and does not go with --check')
        raise SystemExit(together(int(jobs), tree or os.environ.get('SE_REPO', WORKING_TREE), scratch, only))
    check = '--check' in only
    if check:
        only.remove('--check')
    elif not os.environ.get('SE_REPO'):
        raise SystemExit('Name a scratch copy of the repository with SE_REPO: this run changes its files. '
                         '(--check alone reads the working tree and changes nothing.)')
    signal.signal(signal.SIGTERM, stopped)
    survivors = []
    stale = 0
    share, shares = 1, 1
    if os.environ.get('SE_SLICE'):
        share, shares = (int(part) for part in os.environ['SE_SLICE'].split('/'))
    listed = None
    if os.environ.get('SE_ONLY'):
        listed = set(line.strip() for line in Path(os.environ['SE_ONLY']).read_text(encoding='utf-8').splitlines()
                     if line.strip())
        unknown = listed - set(entry[0] for entry in MUTATIONS)
        if unknown:
            raise SystemExit('SE_ONLY names labels that are not in the list: ' + '; '.join(sorted(unknown)))
    chosen = [entry for entry in MUTATIONS
              if entry[3] is not None and (not only or any(word in entry[0] for word in only))
              and (listed is None or entry[0] in listed)]
    for index, (label, name, old, new) in enumerate(chosen):
        if index % shares != share - 1:
            continue
        path = ADDON / name
        # Bytes in, bytes out: on Windows a text file would be written back with
        # other line ends than the game's files have.
        text = path.read_bytes().decode('utf-8')
        if text.count(old) != 1:
            stale += 1
            print('??    %s: the text to change occurs %d times' % (label, text.count(old)), flush=True)
            continue
        if check:
            continue
        path.write_bytes(text.replace(old, new).encode('utf-8'))
        try:
            last, failed = run()
        finally:
            path.write_bytes(text.encode('utf-8'))
        if failed:
            print('caught  %-52s %d: %s' % (label, len(failed), '; '.join(f[:60] for f in failed[:3])), flush=True)
        else:
            survivors.append(label)
            print('MISSED  %s (%s)' % (label, last), flush=True)
    print()
    if check:
        print('%d of %d entries no longer fit the code' % (stale, len(MUTATIONS)))
        return
    print('%d not caught: %s' % (len(survivors), ', '.join(survivors)))


if __name__ == '__main__':
    main()
